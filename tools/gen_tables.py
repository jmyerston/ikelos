"""Generate ``pymorpheus/consts.py`` and ``pymorpheus/keytables.py`` from
the C headers, so numeric constants and key tables can never drift from C.

    python tools/gen_tables.py
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
import os

# C Morpheus checkout (default: sibling directory ../morpheus)
SRC = Path(os.environ.get("MORPHEUS_HOME", Path(__file__).resolve().parents[2] / "morpheus")) / "src"
PKG = HERE.parent / "pymorpheus"

HEADERS = [
    "includes/greek.h",
    "includes/stemtype.h",
    "includes/dialect.h",
    "includes/morphflags.h",
    "includes/prntflags.h",
    "includes/endtags.h",
    "includes/gkstring.h",
    "includes/contract.h",
]

DEFINE = re.compile(r"^\s*#\s*define\s+([A-Za-z_]\w*)\s+(.+?)\s*$")
IDENT = re.compile(r"[A-Za-z_]\w*")


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//.*", "", text)


def c_expr_to_py(expr: str) -> str:
    expr = re.sub(r"\((?:Dialect|Stemtype|long|int|char)\)", "", expr)
    # octal literals
    expr = re.sub(r"\b0([0-7]+)\b", r"0o\1", expr)
    expr = expr.replace("/", "//")
    return expr


def collect_defines() -> dict[str, int]:
    raw: dict[str, str] = {}
    for rel in HEADERS:
        text = strip_comments((SRC / rel).read_text(encoding="latin-1"))
        for line in text.splitlines():
            m = DEFINE.match(line)
            if not m:
                continue
            name, body = m.groups()
            if "(" in name or name in raw:
                continue
            raw[name] = body
    values: dict[str, int] = {}
    changed = True
    while changed:
        changed = False
        for name, body in raw.items():
            if name in values:
                continue
            py = c_expr_to_py(body)
            idents = IDENT.findall(re.sub(r"\b0o[0-7]+|\b\d+", " ", py))
            if any(i not in values for i in idents):
                continue
            try:
                v = eval(py, {"__builtins__": {}}, dict(values))
            except Exception:
                continue
            if isinstance(v, int):
                values[name] = v
                changed = True
    return values


TABLE = re.compile(r"Morph_args\s+(arg_\w+)\[\]\s*=\s*\{(.*?)\n\};", re.S)
STEMCLASS = re.compile(r"arg_stemclass\[\]\s*=\s*\{(.*?)\n\};", re.S)
ENTRY = re.compile(r'"([^"]*)"\s*,\s*([^,]+?)\s*,\s*(\w+)\s*,')
CLASS_ENTRY = re.compile(r'"([^"]*)"\s*,\s*([^,]+?)\s*,')


def main() -> None:
    values = collect_defines()

    out = ['"""Constants from src/includes/*.h. Generated by tools/gen_tables.py; do not edit."""', ""]
    for name in sorted(values):
        out.append(f"{name} = {values[name]}")
    (PKG / "consts.py").write_text("\n".join(out) + "\n")

    text = strip_comments((SRC / "morphlib/morphkeys.h").read_text(encoding="latin-1"))

    def ev(expr: str) -> int:
        return eval(c_expr_to_py(expr), {"__builtins__": {}}, dict(values))

    out = [
        '"""Key tables from src/morphlib/morphkeys.h. Generated by tools/gen_tables.py; do not edit.',
        "",
        "Each table is a tuple of (key, flags, setter) in C order; setter names a",
        'function of src/morphlib/new_val.c ("new_case" etc.).',
        '"""',
        "",
    ]
    m = STEMCLASS.search(text)
    rows = [(k, ev(v)) for k, v in CLASS_ENTRY.findall(m.group(1))]
    out.append("arg_stemclass = (")
    out += [f"    ({k!r}, {v}),"for k, v in rows]
    out.append(")")
    out.append("")
    for name, body in TABLE.findall(text):
        rows = [(k, ev(v), f) for k, v, f in ENTRY.findall(body)]
        out.append(f"{name} = (")
        out += [f"    ({k!r}, {v}, {f!r})," for k, v, f in rows]
        out.append(")")
        out.append("")
    (PKG / "keytables.py").write_text("\n".join(out))
    print(f"{len(values)} constants; tables written")


if __name__ == "__main__":
    main()
